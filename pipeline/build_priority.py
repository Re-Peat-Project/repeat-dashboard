"""Publish the national KHG prioritisation to the app as plain tables: app/public/data/priority/.

    python build_priority.py            # skips when the sources have not changed
    python build_priority.py --force

Reads the outputs of `repeat-national-final` and `repeat-national-dashboard` in <REPEAT_WORK>/national_profile/
(final/, dashboard_data.json, monthly/, overlay_all/) and the Indonesian labels of the prioritisation page
(repeat-prioritisation .../national/assets/i18n_id.js). Nothing is written there: this script only reads.

Written:
  khg_profile.csv          one row per KHG: every column of final_khg.csv (scores, type, ranks, flags, indicators at full
                           precision) plus the profile fields of the dashboard (data confidence, team, this year's hotspots,
                           SiTMAT, villages, peat shares, map bounds). Replace this file to update the KHG numbers.
  khg_series.csv           long table of the per-KHG series: burned (year, % of peat), hs (year, VIIRS count), now_m (month,
                           on peat, in KHG), hm (year, month, medium, high), deficit, rain (year, mm), lc (class, % of KHG).
  khg_landstatus.csv       peat, burned peat and hotspots per land-status layer and class (forest area, peat function,
                           licences, 5 km ring, target and DMPG villages).
  khg_dmpg_villages.csv    DMPG villages reaching into each KHG, with their bounds for zooming.
  khg_tenure_area.csv,
  khg_tenure_hotspots.csv  fire by land tenure: peat per tenure class and hotspots per class and year.
  khg_hotspots_now.csv     this year's MODIS hotspot points per KHG (lon, lat, month, high confidence, on peat).
  khg_geo.json             KHG outlines as GeoJSON (the national map of the prioritisation).
  priority_meta.json       the rule (dimensions, weights, directions, tercile cuts, types), run dates, export list.
  i18n_id.json             the Indonesian labels of the prioritisation page, keyed by the English text.
  exports/                 the files offered by the "Export data" menu, copied as written by the pipeline.

Licence-holder names are not exported.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from datetime import date
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
WORK = HERE.parents[1]
BASE = Path(os.environ.get("REPEAT_WORK", WORK / "re-peat" / "reports")) / "national_profile"
HUB = Path(os.environ.get("REPEAT_HUB", WORK / "re-peat"))
I18N = WORK / "repeat-prioritisation" / "src" / "repeat_prioritisation" / "national" / "assets" / "i18n_id.js"
OUT = HERE.parent / "app" / "public" / "data" / "priority"

INFO = ["kab", "peat_gfw", "peat_gpm", "hs_now", "hs_now_high", "rank_now", "rank_now_n", "tma_n", "tma_deep", "infra", "desa", "dmpg", "dmpg_km2"]
K_FIELDS = ["area", "conf", "team", "ref_rank", "has", "n1h", "n1hn", "lf_prot", "lf_prod", "lf_apl", "lf_dmpg"]


def code_of(kid):
    """KHG.14.10.03 -> 14.10.03 (the code used in the app's routes)."""
    return re.sub(r"^KHG\.", "", kid)


def fingerprint():
    srcs = [BASE / "dashboard_data.json", I18N, I18N.with_name("defs.js"), *sorted((BASE / "final").glob("*")), *sorted((BASE / "monthly").glob("*.csv")),
            *sorted((BASE / "overlay_all").glob("*.csv")), *sorted((BASE / "overlay_all").glob("*.txt")), Path(__file__)]
    from repeat_prioritisation.national.dashboard import EXPORTS
    srcs += [(HUB / r[4:]) if r.startswith("hub:") else BASE / r for r, _ in EXPORTS]
    h = hashlib.sha256()
    for p in srcs:
        if p.exists():
            st = p.stat()
            h.update(f"{p}:{st.st_size}:{st.st_mtime_ns}".encode())
    return h.hexdigest()


def i18n():
    """i18n_id.js holds `const ID={...};` with one JSON string pair per line."""
    s = I18N.read_text(encoding="utf-8").strip()
    s = s[s.index("{"): s.rindex("}") + 1]
    s = re.sub(r"(?m)^\s*//.*$", "", s)            # comment lines
    s = re.sub(r",\s*}$", "}", s)                   # trailing comma
    return json.loads(s)


DEFS = I18N.with_name("defs.js")
DEFS_OUT = HERE.parent / "app" / "src" / "priority" / "defs.gen.js"
DEFS_NAMES = ["TYPE_ORDER", "TYPE_LABEL", "TYPE_NOTE", "TYPE_RULE", "DIMS", "DIM_TIP", "SCORE_NOTE", "IND", "IV_ORDER", "IV_SHORT", "IV_NOTE", "IV_COL", "FIELD_SRC"]


def write_defs():
    """The prioritisation's shared definitions (types, dimensions, indicators, interventions, field sources), wrapped as a module
    so the app uses the same labels and formats as the prioritisation page. Generated: edit defs.js in repeat-prioritisation."""
    body = DEFS.read_text(encoding="utf-8")
    js = ("// Generated by repeat-dashboard/pipeline/build_priority.py from repeat-prioritisation .../national/assets/defs.js. Do not edit.\n"
          "/* eslint-disable */\n// @ts-nocheck\n"
          "export function makeDefs({ t, fx, fmt }) {\n" + body + f"\nreturn {{ {', '.join(DEFS_NAMES)}, pc }};\n}}\n")
    DEFS_OUT.parent.mkdir(parents=True, exist_ok=True)
    DEFS_OUT.write_text(js, encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    try:
        from repeat_prioritisation.national.dashboard import EXPORTS, attach_monthly, attach_overlay_all, final_payload
    except ImportError as e:
        sys.exit(f"needs repeat-prioritisation installed in this environment ({e})")
    if not (BASE / "final" / "final_khg.csv").exists() or not (BASE / "dashboard_data.json").exists():
        sys.exit(f"{BASE}: run repeat-national-final and repeat-national-dashboard first")
    fp = fingerprint()
    stamp = OUT / ".build_cache.json"
    if not a.force and stamp.exists() and json.loads(stamp.read_text())["fingerprint"] == fp:
        print("priority: unchanged, skipped (--force to rebuild)")
        return

    blob = json.loads((BASE / "dashboard_data.json").read_text(encoding="utf-8"))
    data, profiles = blob["data"], blob["profiles"]
    attach_monthly(BASE, profiles)          # the same steps the dashboard applies before it writes its page
    attach_overlay_all(BASE, profiles)
    fin = final_payload(BASE)
    K = data["khg"]
    ki = {k: i for i, k in enumerate(K["id"])}

    # ------------------------------------------------------------ khg_profile.csv
    f = pd.read_csv(BASE / "final" / "final_khg.csv", dtype={"khg_code": str})
    missing = [k for k in f.khg_code if k not in ki]
    if missing:
        sys.exit(f"final_khg.csv has {len(missing)} KHG the dashboard data lacks, e.g. {missing[:3]}")
    prof = pd.DataFrame({"code": [code_of(k) for k in f.khg_code],
                         "name": fin["f"]["name"], "small": fin["f"]["small"]})
    for c in K_FIELDS:
        if c in K:
            prof[c] = [K[c][ki[k]] for k in f.khg_code]
    for c in INFO:
        prof[c] = [((profiles.get(k) or {}).get("info") or {}).get(c) for k in f.khg_code]
    lay = lambda k: (profiles.get(k) or {}).get("lay") or {}
    for j, c in enumerate(["west", "south", "east", "north"]):
        prof[c] = [(lay(k).get("bounds") or [None] * 4)[j] for k in f.khg_code]
    prof["now_total"] = [lay(k).get("now_total") for k in f.khg_code]
    prof["ov"] = [int("ov" in (profiles.get(k) or {})) for k in f.khg_code]
    prof["ov_whole"] = [int(bool(((profiles.get(k) or {}).get("ov") or {}).get("whole"))) for k in f.khg_code]
    prof["tn_end"] = [((profiles.get(k) or {}).get("tn") or {}).get("end") for k in f.khg_code]
    prof = pd.concat([prof, f.drop(columns=["khg_name"])], axis=1)
    for c in ("has", "small", "ov", "ov_whole"):
        prof[c] = prof[c].fillna(0).astype(int)

    # ------------------------------------------------------------ long tables
    series, land, vil, ta, th, pts = [], [], [], [], [], []
    for kid in f.khg_code:
        P, code = profiles.get(kid) or {}, code_of(kid)
        for s in ("burned", "hs", "deficit", "rain"):
            series += [(code, s, r[0], None, r[1], None, None) for r in P.get(s) or []]
        series += [(code, "now_m", r[0], None, r[1], r[2], None) for r in P.get("now_m") or []]
        series += [(code, "hm", r[0], r[1], r[2], r[3], None) for r in P.get("hm") or []]
        series += [(code, "lc", None, None, r[1], None, r[0]) for r in P.get("lc") or []]
        ov = P.get("ov")
        if ov:
            for layer, rows in ov["s"].items():
                for r in rows:
                    land.append((code, layer, r[0], *r[1:5], *(r[5:7] if len(r) > 5 else (None, None))))
            ob = ((P.get("lay") or {}).get("ov") or {}).get("ob", {}).get("dmpg", {})
            for v in ov.get("v") or []:
                bb = ob.get(f"{v[0]}, {v[1]}") or [None] * 4
                vil.append((code, *v, *bb))
        tn = P.get("tn")
        if tn:
            ta += [(code, *r) for r in tn.get("a") or []]
            th += [(code, *r) for r in tn.get("h") or []]
        pts += [(code, *p) for p in (P.get("lay") or {}).get("now") or []]

    OUT.mkdir(parents=True, exist_ok=True)
    w = lambda df, name: df.to_csv(OUT / name, index=False, lineterminator="\n")
    w(prof, "khg_profile.csv")
    w(pd.DataFrame(series, columns=["code", "series", "x", "m", "y", "y2", "cls"]).astype({"x": "Int64", "m": "Int64"}), "khg_series.csv")
    w(pd.DataFrame(land, columns=["code", "layer", "class", "area_km2", "peat_km2", "burned_peat_km2", "hs_now_peat", "lindung_km2", "forest_protected_km2"]), "khg_landstatus.csv")
    w(pd.DataFrame(vil, columns=["code", "village", "subdistrict", "programme", "scheme", "area_km2", "peat_km2", "burned_peat_km2", "hs_now_peat", "west", "south", "east", "north"]), "khg_dmpg_villages.csv")
    w(pd.DataFrame(ta, columns=["code", "tenure", "sub", "dmpg", "peat_km2", "burned_peat_km2"]), "khg_tenure_area.csv")
    w(pd.DataFrame(th, columns=["code", "tenure", "sub", "dmpg", "year", "conf", "n"]), "khg_tenure_hotspots.csv")
    w(pd.DataFrame(pts, columns=["code", "lon", "lat", "month", "high", "peat"]), "khg_hotspots_now.csv")

    geo = {"type": "FeatureCollection", "features": [
        {"type": "Feature", "id": i, "properties": {"code": code_of(kid)}, "geometry": {"type": "MultiPolygon", "coordinates": polys}}
        for i, (kid, polys) in enumerate(zip(K["id"], data["geo"]))]}
    (OUT / "khg_geo.json").write_text(json.dumps(geo, separators=(",", ":")), encoding="utf-8")

    # ------------------------------------------------------------ exports, meta, labels
    ex = OUT / "exports"
    shutil.rmtree(ex, ignore_errors=True)
    ex.mkdir()
    items = []
    for rel, desc in EXPORTS:
        src = (HUB / rel[4:]) if rel.startswith("hub:") else BASE / rel
        if not src.exists():
            continue
        name = src.name if not rel.startswith("final/") else "final_" + src.name.replace("final_", "")
        shutil.copyfile(src, ex / name)
        raw = src.read_bytes()
        rows, cols = (raw.count(b"\n") - 1, len(pd.read_csv(src, nrows=0).columns)) if src.suffix == ".csv" else (1, len(json.loads(raw)))
        items.append({"file": name, "desc": desc, "rows": rows, "cols": cols, "kb": round(len(raw) / 1024, 1),
                      "src": f"{rel.replace('hub:', 're-peat/')} · {date.fromtimestamp(src.stat().st_mtime).isoformat()}"})
    m = data["meta"]
    meta = {"rule": fin["meta"],
            "page": {k: m.get(k) for k in ("generated", "period_now", "baseline", "n_khg", "min_area", "min_peat", "hs_klh_to", "hs_firms_from", "n_full", "peat_by_island")},
            "exports": items, "tiles": "https://re-peat-project.github.io/re-peat/reports/national_profile/khg_tiles/"}
    (OUT / "priority_meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    (OUT / "i18n_id.json").write_text(json.dumps(i18n(), ensure_ascii=False, indent=0), encoding="utf-8")
    write_defs()
    stamp.write_text(json.dumps({"fingerprint": fp}))
    print(f"priority: {len(prof)} KHG, {len(series)} series rows, {len(land)} land-status rows, {len(vil)} DMPG villages, "
          f"{len(pts)} hotspot points, {len(items)} export files -> {OUT}")


if __name__ == "__main__":
    main()
