import { chromium } from 'playwright-core'
const b = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } })
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto('http://127.0.0.1:5173/#/khg/16.02.01')
await p.waitForFunction(() => document.querySelector('[data-ready=true]'), { timeout: 30000 })
await p.waitForTimeout(3000)
await p.getByRole('button', { name: 'Repeat burns' }).click()
await p.waitForTimeout(5000)
await p.screenshot({ path: 'tests/screenshots/khg-repeat.png' })
await p.getByRole('button', { name: 'All years' }).click()
await p.waitForTimeout(4000)
await p.screenshot({ path: 'tests/screenshots/khg-allyears.png' })
await p.getByRole('tab', { name: 'Land & accountability' }).click()
await p.waitForTimeout(6000)
await p.screenshot({ path: 'tests/screenshots/khg-land2.png' })
console.log(errs)
await b.close()
